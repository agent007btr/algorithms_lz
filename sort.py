import random
a = [] #пустой список
for _ in range(100): #повторяем 100 раз
    a.append(random.randint(0, 1000000)) #добавляем случайное число от 0 до 1000000
print("Исходный список:", a) #выводим список
def bs(x): #сортировка пузырьком
    c = 0 #счетчик сравнений
    t = True #были ли обмены
    while t: # были обмены
        t = False # сбрасываем 
        for i in range(len(x) - 1): # проходим по списку
            c += 1 # считаем сравнение
            if x[i] < x[i + 1]: # если левый меньше правого
                x[i], x[i + 1] = x[i + 1], x[i] # меняем местами
                t = True # обмен был
        print("После прохода пузырька:", x) # выводим список
    return c  # возвращаем число сравнений
def ss(x):  # сортировка выбором
    c = 0  # счетчик сравнений
    for i in range(len(x)):  # проходим по списку
        m = i  # индекс максимума
        for j in range(i + 1, len(x)):  # ищем максимум в остатке
            c += 1  # считаем сравнение
            if x[j] > x[m]:  # если нашли больше
                m = j  # запоминаем индекс
        x[i], x[m] = x[m], x[i]  # меняем местами
        print("После прохода выборки:", x)  # выводим список
    return c  # возвращаем число сравнений
print("Сортировка пузырьком") #заголовок
c1 = bs(a.copy()) #запускаем пузырек на копии
print("Сортировка выбором ") #заголовок
c2 = ss(a.copy()) #запускаем выборку на копии
print("Отсортированный список:", sorted(a, reverse=True)) #отсортированный список
print("Количество сравнений в пузырьке:", c1) #сравнения пузырька
print("Количество сравнений в выборке:", c2) #сравнения выборки