import random
a = [] #пустой список
while len(a) < 100: #пока в списке меньше 100 элементов
    n = random.randint(0, 1000000) #генерируем случайное число
    if n not in a: #если числа еще нет в списке
        a.append(n) #добавляем число
a.sort() #сортируем список
print("Отсортированный список:", a) #выводим список
x = a[42] #искомое число
print("Искомое число:", x) #выводим искомое число
c1 = 0 #счетчик сравнений
i1 = -1 #индекс (по умолчанию -1)
for i in range(len(a)): #проходим по списку
    c1 += 1 #считаем сравнение
    if a[i] == x: #если нашли
        i1 = i #запоминаем индекс
        break #выходим из цикла
print("Линейный поиск ") #заголовок
print("Индекс:", i1) #выводим индекс
print("Количество сравнений:", c1) #выводим сравнения
c2 = 0 #счетчик сравнений
i2 = -1 #индекс
l = 0 #левая граница
r = len(a) - 1 #правая граница
while l <= r: #пока границы не пересеклись
    c2 += 1 #считаем сравнение
    m = (l + r) // 2 #находим середину
    if a[m] == x: #если нашли
        i2 = m #запоминаем индекс
        break #выходим из цикла
    elif a[m] < x: #если середина меньше
        l = m + 1 #сдвигаем левую границу
    else: #если середина больше
        r = m - 1 #сдвигаем правую границу
print(" Бинарный поиск ") #заголовок
print("Индекс:", i2) #выводим индекс
print("Количество сравнений:", c2) #выводим сравнения